// Vendor the thinking-orbs engine (MIT, https://github.com/Jakubantalik/Libraries.dev,
// packages/thinking-orbs) into alpaca/web/vendor/thinking-orbs.js as one plain ES module.
//
// The hub has no npm build step, so this strips the TypeScript and wraps each source file in a
// function scope, in dependency order. Only the zero-dependency engine is taken; the React
// wrapper is not. Types are stripped by Node's own stripTypeScriptTypes when the Node build has
// it; otherwise set TYPESCRIPT to any typescript/lib/typescript.js and its transpileModule is used.
//
//   git clone --depth 1 https://github.com/Jakubantalik/Libraries.dev.git <dir>
//   node setup/vendor_thinking_orbs.mjs <dir>/packages/thinking-orbs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire, stripTypeScriptTypes } from 'node:module';
import { execFileSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = process.argv[2];
if (!pkg) { console.error('usage: node setup/vendor_thinking_orbs.mjs <path to packages/thinking-orbs>'); process.exit(2); }
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'alpaca', 'web', 'vendor', 'thinking-orbs.js');

// Dependency order; types.ts carries no runtime code.
const FILES = ['engine/core', 'engine/profiles', 'engine/orbits', 'engine/lattice', 'engine/morph',
  'engine/braid', 'engine/ribbon', 'engine/web', 'engine/registry', 'presets'];
const id = (f) => '__' + f.split('/').pop();

function resolveFrom(file, spec) {
  const parts = dirname(file).split('/').filter((p) => p && p !== '.');
  for (const s of spec.split('/')) { if (s === '..') parts.pop(); else if (s !== '.') parts.push(s); }
  return parts.join('/');
}

function strip(source) {
  if (process.env.TYPESCRIPT) {
    const ts = createRequire(import.meta.url)(process.env.TYPESCRIPT);
    return ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext } }).outputText;
  }
  return stripTypeScriptTypes(source);
}

const blocks = [];
for (const file of FILES) {
  let js = strip(readFileSync(join(pkg, 'src', file + '.ts'), 'utf8'));
  const names = [];
  js = js.replace(/^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?\s*$/gm, (_, list, spec) => {
    const dep = resolveFrom(file, spec);
    if (dep === 'types' || dep === 'engine/types') return '';
    return `const {${list.trim()}} = ${id(dep)};`;
  });
  js = js.replace(/^import\s+'[^']+';?\s*$/gm, '');
  js = js.replace(/^export\s+(function|const|let)\s+([A-Za-z_$][\w$]*)/gm, (_, kw, name) => { names.push(name); return `${kw} ${name}`; });
  if (/^\s*(import|export)\b/m.test(js)) throw new Error(`${file}: unhandled import/export`);
  blocks.push(`// ---- src/${file}.ts\nconst ${id(file)} = (() => {\n${js.trim()}\nreturn { ${names.join(', ')} };\n})();`);
}

let commit = 'unknown';
try { commit = execFileSync('git', ['-C', pkg, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(); } catch {}
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;
const license = readFileSync(join(pkg, 'LICENSE'), 'utf8').trim().split('\n').map((l) => ('// ' + l).trimEnd()).join('\n');

let body = `// thinking-orbs ${version} engine, vendored from https://github.com/Jakubantalik/Libraries.dev
// (packages/thinking-orbs) at commit ${commit}. Generated by setup/vendor_thinking_orbs.mjs;
// do not edit by hand. Upstream license:
//
${license}

${blocks.join('\n\n')}

export const { MODE_FRAMES } = __registry;
export const { resolvePreset, STATE_TO_MODE } = __presets;
export const { paintFrame } = __core;
`;
// The hub serves ASCII only: escape every non-ASCII character (they sit in comments and strings).
body = body.replace(/[^\x00-\x7f]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
writeFileSync(out, body);
console.log(`wrote ${out} (${body.length} bytes, thinking-orbs ${version} @ ${commit.slice(0, 12)})`);
