#: paths the attached repository must never receive; checked on the objects that enter, so a file the
#: repository already had under one of these names does not block every later branch
EXTRA_PROTECTED = (".alpaca/", "ALPACA-MANIFEST", "RESUME.md", "CHECKLIST.md")
#: studio folders whose files are always hashed, under every exclusion below (a planted exclusion cannot hide them)
STUDIO_FOLDERS = ("design", "doctrine", "contracts", "runbooks", "research", ".alpaca/proofs")
#: folders of the studio that hold the attached repository's own bytes (work folders, gate clones and seeds, the `land`
#: scratch, stage evidence, the study's reading copy) or the push folder: a handoff would refuse its own blobs if they
#: counted as studio files (t-686 fix round 1, B2). Real paths below the studio root.
REPO_BYTES_FOLDERS = (STATE_DIR + "/worktrees", STATE_DIR + "/runs", STATE_DIR + "/stages", STATE_DIR + "/study",
                      STATE_DIR + "/push", ".alpaca/worktrees")
#: a research run freezes the repository's files beside the studio's pack: `.alpaca/research/<run>/contract/files/<path>`
#: is a copy of the repository except under `@studio`, which is the pack (and is hashed)
_FROZEN = (".alpaca", "research")
#: folder names skipped at any depth: git's own folders and third-party or generated bytes
SKIPPED_NAMES = (".git", ".venv", "__pycache__", ".pytest_cache", "node_modules")
EMPTY_BLOB = "e69de29bb2d1d6434b8b29ae775ad8c2e48c5391"
_BLOB_ID = re.compile(r"[0-9a-f]{40}|[0-9a-f]{64}")

_PERSON = re.compile(r"^(author|committer) (.*) <([^>]*)> ", re.M)


@dataclass
class ScanResult:
    verdict: int
    refused: bool
    reasons: list = field(default_factory=list)
    commits_scanned: int = 0
    objects_scanned: int = 0
    report: dict = field(default_factory=dict)
    #: the ids of the objects the scan read as entering (t-686 fix round 2, B3): the push sends exactly these
    object_ids: frozenset = frozenset()

    @property
    def reason(self) -> str:
        """One printable line: the reason codes and the report's detail lines. No matched text."""
        return "; ".join(list(self.reasons) + list(self.report.get("detail", [])))


# ------------------------------------------------------------------------------------ the term list

def _policy(root):
    """(project config, TermList with the attach minimum added). Raises ValueError when the studio's
    term list is missing, empty or unusable (the release policy refuses it)."""
    from alpaca.release import checks
    try:
        cfg, tl, _digest = checks.policy(root)
    except ValueError:
        raise
    except Exception as exc:
        raise ValueError("the term list or project.yaml could not be read (%s)" % type(exc).__name__) from None
    own_allow = list(getattr(tl, "shape_allow", ()))
    _add_minimum(tl, root, cfg)
    tl.own_shape_allow = own_allow
    return cfg, tl


def _add_minimum(tl, root, cfg) -> None:
    """Add the attach minimum terms to `tl` in memory (nothing is written)."""
    have = {key for _term, key in tl.terms}
    literals = [os.path.realpath(str(root)), os.path.realpath(os.path.expanduser("~"))]
    if cfg.get("project_id"):
        literals.append(str(cfg["project_id"]))
    for term in literals:
        key = leak_audit.defang(term).casefold()
        if len(term) >= leak_audit.MIN_TERM_LEN and term != os.sep and key not in have:
            have.add(key)
            tl.terms.append((term, key))
    for line in ATTACH_MINIMUM:
        rx, brx = leak_audit._compile_regex(line[len("re:"):].strip())
        tl.regexes.append(("attach minimum", rx, brx))
    # the attach commit identity is not a leak; every other mailbox still meets the shape rule
    attached = config.mode(root)
    email = attached.identity[1] if attached is not None else gitops.IDENTITY[1]
    tl.shape_allow = list(getattr(tl, "shape_allow", ())) + [(re.compile(re.escape(email), re.I),
                                                              "attach agent identity", 0)]


def term_list(root):
    """The studio's sealed-term list with the attach minimum added. Raises ValueError when unusable."""
    return _policy(root)[1]


def _hits(tl, text, name) -> bool:
    found, _suppressed = leak_audit.scan_text(tl, text, name, shape_on=True)
    return bool(found) or barrier._meta_hits(tl, text)


def text_problems(root, text, name) -> list:
    """Problems of one outgoing text (a pull request title or body, a branch name), one line each. The line
    never repeats the text."""
    try:
        tl = term_list(root)
    except ValueError as exc:
        return ["%s cannot be checked: %s" % (name, exc)]
    if _hits(tl, text, name):
        return ["%s holds a studio string or a sealed term" % name]
    return []


# ------------------------------------------------------------------------------------ studio blobs

def blob_sizes(text, count) -> set:
    """The sizes of the blobs in the output of `git cat-file --batch-check='%(objecttype) %(objectsize)'` for `count`
    objects. Anything but one line per object, each a commit, tree, tag or blob, raises AttachError."""
    lines = text.splitlines()
    if len(lines) != count:
        raise AttachError("the sizes of the entering objects could not be read")
    found = set()
    for line in lines:
        kind, _, size = line.partition(" ")
        if kind == "blob" and size.isdigit():
            found.add(int(size))
        elif kind not in ("commit", "tree", "tag"):
            raise AttachError("an entering object could not be sized (%s)" % kind[:20])
    return found


def _entering_sizes(worktree, objects) -> set:
    shas = [sha for sha, _path in objects]
    if not shas:
        return set()
    done = gitops.run(worktree, "cat-file", "--batch-check=%(objecttype) %(objectsize)", input="\n".join(shas) + "\n",
                      timeout=300)
    if done.rc != 0:
        raise AttachError("the sizes of the entering objects could not be read")
    return blob_sizes(done.out, len(shas))


def _frozen_repo_copy(parts) -> bool:
    """True for a path (as parts below the studio root) inside `.alpaca/research/<run>/contract/files/` that is not under
    `@studio`: the repository's own file, frozen for a research run."""
    return len(parts) >= 6 and tuple(parts[:2]) == _FROZEN and tuple(parts[3:5]) == ("contract", "files") and parts[5] != "@studio"


def _walk_files(base, real, skip_paths, skip_names, skip_frozen) -> list:
    """Absolute paths of the regular files under `base` (links neither followed nor listed), without the folders in
    `skip_paths`, the folder names in `skip_names` and, with `skip_frozen`, the research runs' frozen repository files."""
    found = []
    if os.path.islink(base) or not os.path.isdir(base):
        return found
    for folder, dirs, names in os.walk(base, followlinks=False):
        rel = os.path.relpath(folder, real).split(os.sep) if folder != real else []
        dirs[:] = [d for d in dirs if d not in skip_names and os.path.join(folder, d) not in skip_paths
                   and not os.path.islink(os.path.join(folder, d)) and not (skip_frozen and _frozen_repo_copy(rel + [d]))]
        for name in names:
            if not (skip_frozen and _frozen_repo_copy(rel + [name])):
                found.append(os.path.join(folder, name))
    return found


def hash_files(root, paths) -> set:
    """Blob ids of `paths` (`git hash-object --no-filters`). A batch git cannot finish (one file unreadable or gone)
    is hashed file by file, so one bad file never hides the others."""
    found = set()

    def one(path):
        done = gitops.run(root, "hash-object", "--no-filters", "--", path)
        if done.rc == 0 and _BLOB_ID.fullmatch(done.out.strip()):
            found.add(done.out.strip())

    plain = [p for p in paths if "\n" not in p]
    for start in range(0, len(plain), 500):
        batch = plain[start:start + 500]
        done = gitops.run(root, "hash-object", "--no-filters", "--stdin-paths", input="\n".join(batch) + "\n")
        ids = done.out.split() if done.rc == 0 else []
        if len(ids) == len(batch) and all(_BLOB_ID.fullmatch(x) for x in ids):
            found.update(ids)
        else:
            for path in batch:
                one(path)
    for path in paths:
        if "\n" in path:                                  # --stdin-paths is one path per line
            one(path)
    return found


def studio_blob_set(root, sizes=None) -> set:
    """Blob ids of the studio's own bytes, from sources that do not trust the studio's git history:

      * the studio's working tree: every regular file, tracked, untracked or ignored, `.alpaca/` included, except the
        folders of `REPO_BYTES_FOLDERS`, the research runs' frozen repository files, the attached clone and the names
        in `SKIPPED_NAMES` (a studio made by `alpaca new` has no commit, and its shipped `.gitignore` keeps `.alpaca/`
        and `RESUME.md` out of git, so neither `ls-tree HEAD` nor the tracked set sees them: t-686 adversarial B2);
      * every file under `STUDIO_FOLDERS`, under none of those exclusions;
      * the blobs of the studio's HEAD tree and index, and every blob in the studio's object store, so a file that was
        committed or added once and is gone from the working tree still counts.

    `sizes`, a set of byte counts, keeps only files and stored blobs of one of those sizes, which is how callers bound
    the cost: a studio can hold gigabytes (`alpaca.db`), and a blob that enters the upstream can only equal a file of
    its own size. There is no size cap on that path. With `sizes=None` every file is hashed. The empty blob is dropped."""
    blobs = set()
    done = gitops.run(root, "ls-tree", "-r", "HEAD")
    if done.rc == 0:
        for line in done.out.splitlines():
            meta = line.split("\t", 1)[0].split()
            if len(meta) == 3 and meta[1] == "blob":
                blobs.add(meta[2])
    done = gitops.run(root, "ls-files", "-s")
    if done.rc == 0:
        for line in done.out.splitlines():
            meta = line.split("\t", 1)[0].split()
            if len(meta) == 3 and meta[0] != "160000" and _BLOB_ID.fullmatch(meta[1]):
                blobs.add(meta[1])
    done = gitops.run(root, "cat-file", "--batch-all-objects", "--batch-check=%(objecttype) %(objectname) %(objectsize)",
                      timeout=600)
    if done.rc == 0:
        for line in done.out.splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[0] == "blob" and parts[2].isdigit() and (sizes is None or int(parts[2]) in sizes):
                blobs.add(parts[1])
    real = os.path.realpath(str(root))
    skip = {os.path.join(real, *rel.split("/")) for rel in REPO_BYTES_FOLDERS}
    cfg = config.mode(root)
    if cfg is not None:
        clone = os.path.realpath(str(cfg.repo_path(root)))
        if clone.startswith(real + os.sep):                # never skip the root itself
            skip.add(clone)
    files = set(_walk_files(real, real, skip, SKIPPED_NAMES, True))
    for rel in STUDIO_FOLDERS:
        files.update(_walk_files(os.path.join(real, *rel.split("/")), real, set(), (), False))
    wanted = []
    for path in sorted(files):
        try:
            info = os.lstat(path)
        except OSError:
            continue
        if stat.S_ISREG(info.st_mode) and info.st_size > 0 and (sizes is None or info.st_size in sizes):
            wanted.append(path)
    blobs.update(hash_files(root, wanted))
    blobs.discard(EMPTY_BLOB)
    return blobs


# ------------------------------------------------------------------------------------ research packs

def pack_blob_set(root) -> set:
    """Blob ids of every file of a research pack the studio holds: the folders `research/` and the studio folder
    of every frozen research runbook, and the frozen copies a run keeps under `.alpaca/research/<run>/contract/files/@studio`
    (the owner may have edited a pack since a run read it). A pack never reaches the attached repository
    (t-653 follow-up: `land` is the only check between a pack file and a push for patches that come through it,
    so the handoff checks every object that enters)."""
    from alpaca.attach import runbooks
    folders = tuple(runbooks.PACK_FOLDERS) + tuple(runbooks.recorded_pack_folders(root))
    return runbooks.pack_blob_ids(root, folders)


def pack_path_set(root) -> set:
    """The studio-relative paths of the files of the research packs (`research/` and the folder of each recorded
    research runbook), links neither followed nor listed. An entering object at one of these paths is refused even
    when its bytes differ: a pack file edited on a work branch is still a pack file."""
    from alpaca.attach import runbooks
    real = os.path.realpath(str(root))
    found = set()
    for name in tuple(runbooks.PACK_FOLDERS) + tuple(runbooks.recorded_pack_folders(root)):
        base = os.path.join(real, name)
        if os.path.islink(base) or not os.path.isdir(base):
            continue
        for folder, dirs, names in os.walk(base, followlinks=False):
            dirs[:] = [d for d in dirs if d not in ("__pycache__", ".git") and not os.path.islink(os.path.join(folder, d))]
            for leaf in names:
                full = os.path.join(folder, leaf)
                if not os.path.islink(full) and os.path.isfile(full):
                    found.add("/".join(os.path.relpath(full, real).split(os.sep)))
    return found


# ------------------------------------------------------------------------------------ the copied object store

#: where the scan's copy and the push folder live, below the studio root (`REPO_BYTES_FOLDERS` leaves it out of the studio
#: blob set: it holds the repository's own bytes)
COPY_DIR = STATE_DIR + "/push"
#: `-c` values of every git that walks or packs objects for the scan or the push (t-686 fix round 2, B3). Each file git keeps
#: beside the objects that can change which objects a walk reaches or a push sends: the commit-graph (a parent the commit
#: does not have), the multi-pack-index and the reachability bitmaps (a list of objects decided when they were written), and
#: the sparse tree walk (which may send objects the plain walk leaves out). Replace refs and grafts are off in
#: `gitops.clean_env`; the shallow file is `NO_SHALLOW`.
STORE_OFF = ("core.commitGraph=false", "core.multiPackIndex=false", "pack.useBitmaps=false", "pack.useSparse=false")
#: GIT_SHALLOW_FILE for the same commands: a path that cannot exist (a file below /dev/null), so git reads no shallow file and
#: walks the real parents. An existing empty file would make git read the repository as shallow (investigate-r2-probe.log, I).
NO_SHALLOW = os.devnull + "/none"
_PACK_TYPES = {b"commit": 1, b"tree": 2, b"blob": 3, b"tag": 4}


def store_env() -> dict:
    env = gitops.clean_env()
    env["GIT_SHALLOW_FILE"] = NO_SHALLOW
    return env


def _store_git(repo, *args, input=None, timeout=600):
    """`git -C repo -c <STORE_OFF> args` (bytes out) under `store_env`; a non-zero exit raises AttachError."""
    pairs = [x for kv in STORE_OFF for x in ("-c", kv)]
    done = gitops.run(repo, *pairs, *args, input=input, binary=True, env=store_env(), timeout=timeout)
    if done.rc != 0:
        raise AttachError("git %s failed: %s" % (args[0], " ".join(gitops.scrub(done.err.decode("utf-8", "replace")).split())[-200:]
                                                 or "exit %d" % done.rc))
    return done.out


def object_walk(repo, head, base) -> list:
    """The objects reachable from `head` and not from `base` (`git rev-list --objects head --not base`), as
    `(sha, path bytes)`, walked over the real parents of each commit: no commit-graph, multi-pack-index, bitmap, replace
    ref, graft or shallow file is read."""
    found = []
    for line in _store_git(repo, "rev-list", "--objects", head, "--not", base).split(b"\n"):
        if line:
            sha, _, path = line.partition(b" ")
            found.append((sha.decode("ascii"), path))
    return found


def _object_hash(sha):
    return "sha256" if len(sha) == 64 else "sha1"


def read_objects(repo, shas) -> dict:
    """`{sha: (type bytes, data bytes)}` of `shas` read from `repo` (`git cat-file --batch`), each checked against its
    name: the hash of `<type> <size>NUL<data>` must be the sha. A missing object or one whose bytes do not give its name
    raises AttachError, so a packfile, loose object or alternate store changed to hold other bytes under a name is
    refused, never copied (investigate-r2-probe.log, E)."""
    shas = sorted(set(shas))
    if not shas:
        return {}
    out = _store_git(repo, "cat-file", "--batch", input=("\n".join(shas) + "\n").encode("ascii"))
    found, pos = {}, 0
    for sha in shas:
        end = out.find(b"\n", pos)
        head = out[pos:end].split(b" ") if end >= 0 else []
        if len(head) != 3 or head[0].decode("ascii", "replace") != sha or head[1] not in _PACK_TYPES or not head[2].isdigit():
            raise AttachError("the object %s could not be read from the clone" % sha[:12])
        size = int(head[2])
        data = out[end + 1:end + 1 + size]
        if len(data) != size or out[end + 1 + size:end + 2 + size] != b"\n":
            raise AttachError("the object %s could not be read from the clone" % sha[:12])
        name = hashlib.new(_object_hash(sha), b"%s %d\0" % (head[1], size) + data).hexdigest()
        if name != sha:
            raise AttachError("the bytes the clone holds under %s are not that object; nothing is copied" % sha[:12])
        found[sha] = (head[1], data)
        pos = end + 2 + size
    return found


def _pack_bytes(objects, algo) -> bytes:
    """A version 2 packfile of `objects` (`{sha: (type, data)}`), no deltas."""
    out = bytearray(b"PACK" + struct.pack(">II", 2, len(objects)))
    for sha in sorted(objects):
        typ, data = objects[sha]
        n = len(data)
        byte, n = (_PACK_TYPES[typ] << 4) | (n & 0x0F), n >> 4
        while n:
            out.append(byte | 0x80)
            byte, n = n & 0x7F, n >> 7
        out.append(byte)
        out += zlib.compress(data)
    out += hashlib.new(algo, bytes(out)).digest()
    return bytes(out)


def _support(repo, head, base) -> set:
    """The objects a walk of `head --not base` reads on the side of `base` besides the ones it lists: the commits of `base`
    that `head` does not have (git walks them to find where the two meet), and each boundary commit (a parent the walk
    stops at) with every tree of it (git marks those trees' entries as already there). No blob: a walk only flags those."""
    commits = set(_store_git(repo, "rev-list", base, "--not", head).decode("ascii").split())
    boundary = {line[1:] for line in _store_git(repo, "rev-list", "--boundary", head, "--not", base).decode("ascii").split()
                if line.startswith("-")}
    trees = set()
    for sha, (_typ, data) in read_objects(repo, boundary).items():
        first = data.split(b"\n", 1)[0]
        if not first.startswith(b"tree "):
            raise AttachError("the commit %s has no tree line" % sha[:12])
        root_tree = first[5:].decode("ascii")
        trees.add(root_tree)
        for row in _store_git(repo, "ls-tree", "-r", "-t", "-z", root_tree).split(b"\0"):
            meta = row.split(b"\t", 1)[0].split()
            if len(meta) == 3 and meta[1] == b"tree":
                trees.add(meta[2].decode("ascii"))
    return commits | boundary | trees | {head, base}


def folder_state(folder) -> tuple:
    """Every name under `folder` with its type, mode, size, change time and inode (links not followed): equal states mean
    nothing was added, removed or rewritten in between."""
    rows = []
    for here, dirs, names in os.walk(folder, followlinks=False):
        for name in sorted(dirs + names):
            path = os.path.join(here, name)
            try:
                st = os.lstat(path)
            except OSError:
                rows.append((os.path.relpath(path, folder), "gone"))
                continue
            rows.append((os.path.relpath(path, folder), st.st_mode, st.st_size, st.st_mtime_ns, st.st_ctime_ns, st.st_ino))
    return tuple(sorted(rows, key=lambda row: row[0]))


def copy_store(root, repo, head, base, label) -> tuple:
    """A fresh bare repository below `COPY_DIR` holding exactly the objects of `head --not base` that `repo` has, plus the
    `base` side objects a walk reads (`_support`), and nothing else: no alternates, refs, hooks, commit-graph, bitmap or
    multi-pack-index. Every object is read from `repo` and checked against its name before it is written (`read_objects`),
    then the copy is proved: its object list is exactly what was written, and its own walk of `head --not base` gives the
    same objects as the walk in `repo`. Returns `(relative path, folder, walk, state)`; `walk` is `[(sha, path bytes)]`,
    `state` the `folder_state` after the proof. The caller removes the folder (`safefs.remove_tree`). (t-686 fix round 2,
    B3: the push folder of round 1 read the clone's objects through `objects/info/alternates`, and with them the clone's
    commit-graph, bitmaps, multi-pack-index and changed packfiles; `investigate-r2.md`.)"""
    walk = object_walk(repo, head, base)
    wanted = {sha for sha, _p in walk}
    extra = _support(repo, head, base) - wanted
    objects = read_objects(repo, wanted | extra)
    algo = _object_hash(head)
    rel = "%s/%s-%s" % (COPY_DIR, label, secrets.token_hex(6))
    folder = safefs.make_dir(root, rel, exclusive=True)
    try:
        init = ["init", "--bare", "--template=", "-q"] + (["--object-format=sha256"] if algo == "sha256" else [])
        done = gitops.run(folder, *init)
        if done.rc != 0:
            raise AttachError("git init failed for the object copy: %s" % (" ".join(gitops.scrub(done.err).split())[-160:]
                                                                         or "exit %d" % done.rc))
        if objects:
            _store_git(folder, "index-pack", "--stdin", input=_pack_bytes(objects, algo))
        held = set(_store_git(folder, "cat-file", "--batch-all-objects", "--batch-check=%(objectname)").decode("ascii").split())
        if held != set(objects):
            raise AttachError("the object copy holds %d objects, not the %d written" % (len(held), len(objects)))
        if os.path.lexists(os.path.join(folder, "objects", "info", "alternates")):
            raise AttachError("the object copy names another object folder")
        again = object_walk(folder, head, base)
        if {sha for sha, _p in again} != wanted or len(again) != len(walk):
            raise AttachError("the walk of the object copy is not the walk of the clone")
        state = folder_state(folder)
    except BaseException:
        safefs.remove_tree(root, rel)
        raise
    return rel, folder, walk, state


