"""What may leave the studio inside a pull request: the outgoing scan (op-062 t-651, requirement R9).

`outgoing` judges one work branch the way the outbound barrier judges a push, bounded by the commits that
would really enter the upstream, plus what the barrier does not know about an attached studio:

  * the studio's own strings (its real path, the home folder, session and scratch paths, op ids, the
    project id) are added to whatever term list the studio has (build plan P23, `ATTACH_MINIMUM`);
  * a blob that is byte-for-byte a file of the studio (any regular file of its working tree, tracked or not, ignored
    or not, `.alpaca/` included; the blobs of its HEAD, index and object store) is refused under any file name
    (`STUDIO-BLOB-IN-PUSH`). A small generic file whose bytes equal a studio file is refused too; the remedy is to
    change its bytes;
  * the commit identity must be the attach identity or match an allow rule of the project;
  * the branch name, the pull request title and the body are read like a commit message;
  * `.alpaca/`, `ALPACA-MANIFEST`, `RESUME.md` and `CHECKLIST.md` may not enter;
  * a research pack file (the studio's `research/` folder, the folder of each recorded research runbook and the
    frozen copies a run keeps) may not enter, by content or by path (`RESEARCH-PACK-IN-PUSH`, op-062 t-686).

The scan reads a fresh copy of exactly the entering objects (`copy_store`): each read from the repository and checked
against its name, walked over the real parents (no commit-graph, bitmap, multi-pack-index, replace ref, graft or shallow
file), and the handoff pushes from a second copy that must list the same objects (t-686 fix round 2, B3).

A missing, empty or unusable term list refuses. A refusal names reason codes and digests, never the
term, the path or the text that matched, so a report cannot repeat what it guards.

Task ids such as `t-001` are allowed: the work branch is named after one.
"""
