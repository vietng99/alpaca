def _digest(*parts):
    return barrier._digest(*parts)


def _refuse(reasons, detail, commits=0, objects=0):
    report = {"instrument": "attach-outgoing", "commits_scanned": commits, "objects_scanned": objects,
              "verdict": vc.name_of(vc.BLOCKED), "reason_codes": list(reasons), "detail": list(detail),
              "blocked": []}
    return ScanResult(vc.BLOCKED, True, list(reasons), commits, objects, report)


def _repository(root, worktree):
    """The folder the scan's git runs in. A task work folder is never used by its own `.git` file, which the
    worker can rewrite (op-062 t-648: `gitops.run` refuses it): its commits and objects live in the attached
    clone, so the clone named by project.yaml is read instead, and a head that is not there is refused as not
    a commit. A work folder of another studio, or a studio that is not attached, gives None (refused). Any
    other folder is read as given."""
    if not gitops.in_work_folder(worktree):
        return worktree
    cfg = config.mode(root)
    if cfg is None:
        return None
    mine = os.path.join(os.path.realpath(str(root)), STATE_DIR, "worktrees") + os.sep
    if not os.path.realpath(str(worktree)).startswith(mine):
        return None
    return str(cfg.repo_path(root))


def _is_commit(worktree, sha) -> bool:
    if not isinstance(sha, str) or not re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", sha) or set(sha) == {"0"}:
        return False
    return gitops.run(worktree, "cat-file", "-e", sha + "^{commit}").rc == 0


def outgoing(root, worktree, head, base, *, branch, title, body) -> ScanResult:
    """Judge what a work branch would send: the commits and objects reachable from `head` and not from
    `base` (the fetched upstream base; never an all-zero value, which would scan the upstream's whole
    history), the branch name, the pull request title and the body. Never raises for a bad input; a
    refusal comes back as a ScanResult with `refused` true."""
    try:
        cfg, tl = _policy(root)
    except ValueError as exc:
        return _refuse([barrier.R_TERMS_MISSING], ["the studio's term list is missing or unusable, so nothing "
                                                   "can be checked (%s)" % exc])
    worktree = _repository(root, worktree)
    if worktree is None:
        return _refuse([R_BASE], ["the work folder is not a task work folder of this attached studio"])
    # the author every outgoing commit must carry: the studio's one commit identity, proved against the record (t-689)
    attached = config.mode(root)
    try:
        who = proven.identity(root, attached) if attached is not None else gitops.IDENTITY
    except AttachError as exc:
        return _refuse([R_IDENTITY], ["the commit identity cannot be proved (%s)" % gitops.scrub(exc)])
    if not _is_commit(worktree, head):
        return _refuse([R_BASE], ["the branch head is not a commit of the work tree"])
    if not _is_commit(worktree, base):
        return _refuse([R_BASE], ["the upstream base is not a commit the work tree has; fetch and run the "
                                  "check again (a missing base would scan the upstream's whole history)"])
    # the scan reads a copy of exactly the entering objects, each checked against its name, walked over the real parents;
    # the push is made from a second such copy and must list the same objects (t-686 fix round 2, B3)
    try:
        rel, copy, walk, state = copy_store(root, worktree, head, base, "scan")
    except (AttachError, OSError) as exc:
        return _refuse([barrier.R_SCAN_ERROR], ["the objects of the branch could not be copied for the scan, so it is "
                                               "refused (%s)" % (exc if isinstance(exc, AttachError) else type(exc).__name__)])
    try:
        result = _scan_copy(root, copy, head, base, branch=branch, title=title, body=body, cfg=cfg, tl=tl, author=who)
        if not result.refused:
            if result.object_ids != frozenset(sha for sha, _p in walk):
                return _refuse([barrier.R_SCAN_ERROR], ["the scan's walk is not the walk of the clone"],
                               result.commits_scanned, result.objects_scanned)
            if folder_state(copy) != state:
                return _refuse([barrier.R_SCAN_ERROR], ["the scan's object copy changed while it was read"],
                               result.commits_scanned, result.objects_scanned)
        return result
    finally:
        safefs.remove_tree(root, rel)


def _scan_copy(root, worktree, head, base, *, branch, title, body, cfg, tl, author=gitops.IDENTITY) -> ScanResult:
    """The scan of `outgoing`, reading the object copy `worktree`."""
    reasons, detail, blocked, verdicts = [], [], [], []

    def block(code, where, code_verdict=vc.FAIL, **extra):
        blocked.append(dict(where=where, reason=code, **extra))
        if code not in reasons:
            reasons.append(code)
        verdicts.append(code_verdict)

    try:
        with gitops.process_env_scrubbed():
            commits = barrier.commits_entering(worktree, head, base)
            objects = barrier.objects_entering(worktree, head, base)
            result = barrier.scan(str(worktree), [], refs=[("refs/heads/" + str(branch), head)], objects=objects,
                                  cfg=cfg, term_list=tl, terms_base=str(root))
    except Exception as exc:
        return _refuse([barrier.R_SCAN_ERROR], ["the scan could not run, so the branch is refused (%s)"
                                               % type(exc).__name__])
    for code in result.reasons:
        if code not in reasons:
            reasons.append(code)
    verdicts.append(result.verdict)
    blocked.extend(result.report.get("blocked", []))
    detail.extend(result.report.get("detail", []))

    # paths the repository must never receive, judged on the objects that enter
    for sha, path in objects:
        name = path.decode("utf-8", "surrogateescape")
        if path and barrier.path_is_protected(name, EXTRA_PROTECTED):
            block(barrier.R_PROTECTED, "path", vc.BLOCKED, path_digest=_digest(path), object=sha[:12])

    # commit messages and identities
    allow = getattr(tl, "own_shape_allow", ())
    for sha in commits:
        done = gitops.run(worktree, "cat-file", "commit", sha, binary=True)
        raw = done.out if done.rc == 0 else b""
        text = raw.decode("utf-8", "replace")
        if not raw:
            block(barrier.R_SCAN_ERROR, "commit", vc.BLOCKED, commit=sha[:12])
            continue
        if _hits(tl, text, "commit"):
            block(R_TEXT, "commit-message", commit=sha[:12])
        header = text.split("\n\n", 1)[0]
        for who, name, email in _PERSON.findall(header + " "):
            if (name, email) == tuple(author) or any(rx.fullmatch(email) for rx, _why, _n in allow):
                continue
            block(R_IDENTITY, who, vc.BLOCKED, commit=sha[:12])

    # branch name, pull request title and body
    for where, text in (("branch-name", branch), ("pr-title", title), ("pr-body", body)):
        if isinstance(text, str) and text and _hits(tl, text, where):
            block(R_TEXT, where, text_digest=_digest(text))

    # studio files under any name, and research packs by content and by path
    try:
        known = studio_blob_set(root, _entering_sizes(worktree, objects))
        packs = pack_blob_set(root)
        pack_paths = pack_path_set(root)
    except AttachError as exc:
        return _refuse([barrier.R_SCAN_ERROR], ["the studio's files could not be listed (%s)" % exc], len(commits),
                       len(objects))
    for sha, path in objects:
        name = path.decode("utf-8", "surrogateescape")
        if sha in packs or (path and name in pack_paths):
            block(R_PACK, "research-pack", vc.BLOCKED, blob_digest=sha[:12], path_digest=_digest(path))
        elif sha in known:
            block(R_STUDIO_BLOB, "blob", vc.BLOCKED, blob_digest=sha[:12], path_digest=_digest(path))

    verdict = leak_audit.worst(verdicts) if verdicts else vc.PASS
    report = {"instrument": "attach-outgoing", "commits_scanned": len(commits), "objects_scanned": len(objects),
              "verdict": vc.name_of(verdict), "reason_codes": [r for r in reasons if r != barrier.R_NO_COMMITS],
              "detail": detail, "blocked": blocked, "tier": result.report.get("tier", "public")}
    return ScanResult(verdict, verdict != vc.PASS, report["reason_codes"], len(commits), len(objects), report,
                      frozenset(sha for sha, _p in objects))


# ------------------------------------------------------------------------------------ the leak audit lister

def leak_lister(repo):
    """(full path, relative path) of every file git tracks in `repo` or would track (`ls-files --cached
    --others --exclude-standard`), in a fixed order: the repository's own .git folder and what its
    .gitignore keeps out are not part of the tree the leak audit judges. A tracked file that is gone from
    disk and a gitlink are skipped, as the folder walk skips what is not a file."""
    done = gitops.run(repo, "ls-files", "-z", "--cached", "--others", "--exclude-standard", binary=True)
    if done.rc != 0:
        raise AttachError("git ls-files failed in %s" % os.path.basename(str(repo)))
    names = sorted({x for x in done.out.split(b"\0") if x})
    for raw in names:
        rel = raw.decode("utf-8", "surrogateescape")
        full = os.path.join(str(repo), rel)
        if os.path.islink(full) or os.path.isfile(full):
            yield full, leak_audit.canon_path(rel)
